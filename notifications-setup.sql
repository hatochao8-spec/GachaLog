-- GachaLog 通知機能
-- Supabase SQL Editor で一度だけ実行してください。

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  actor_id uuid not null references public.profiles(id) on delete cascade,
  type text not null check (type in ('like','comment','follow')),
  post_id bigint references public.posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  constraint notifications_not_self check (recipient_id <> actor_id)
);

create index if not exists notifications_recipient_created_idx
  on public.notifications (recipient_id, created_at desc);
create index if not exists notifications_unread_idx
  on public.notifications (recipient_id) where read_at is null;

alter table public.notifications enable row level security;

drop policy if exists "Users can read own notifications" on public.notifications;
create policy "Users can read own notifications"
on public.notifications for select to authenticated
using (auth.uid() = recipient_id);

drop policy if exists "Users can mark own notifications read" on public.notifications;
create policy "Users can mark own notifications read"
on public.notifications for update to authenticated
using (auth.uid() = recipient_id)
with check (auth.uid() = recipient_id);

grant select, update on public.notifications to authenticated;
grant usage, select on sequence public.notifications_id_seq to authenticated;

create or replace function public.create_gachalog_like_notification()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare owner_id uuid;
begin
  select p.user_id into owner_id from public.posts p
  where p.id = new.post_id and p.status = 'published';
  if owner_id is not null and owner_id <> new.user_id then
    insert into public.notifications(recipient_id, actor_id, type, post_id)
    values (owner_id, new.user_id, 'like', new.post_id);
  end if;
  return new;
end;
$$;

create or replace function public.create_gachalog_comment_notification()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare owner_id uuid;
begin
  select p.user_id into owner_id from public.posts p
  where p.id = new.post_id and p.status = 'published';
  if owner_id is not null and owner_id <> new.user_id then
    insert into public.notifications(recipient_id, actor_id, type, post_id)
    values (owner_id, new.user_id, 'comment', new.post_id);
  end if;
  return new;
end;
$$;

create or replace function public.create_gachalog_follow_notification()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if new.follower_id <> new.following_id then
    insert into public.notifications(recipient_id, actor_id, type)
    values (new.following_id, new.follower_id, 'follow');
  end if;
  return new;
end;
$$;

drop trigger if exists gachalog_like_notification on public.post_likes;
create trigger gachalog_like_notification
after insert on public.post_likes
for each row execute function public.create_gachalog_like_notification();

drop trigger if exists gachalog_comment_notification on public.comments;
create trigger gachalog_comment_notification
after insert on public.comments
for each row execute function public.create_gachalog_comment_notification();

drop trigger if exists gachalog_follow_notification on public.follows;
create trigger gachalog_follow_notification
after insert on public.follows
for each row execute function public.create_gachalog_follow_notification();
