-- GachaLog: カプセル種類（ラインナップ）と種類別コレクション
-- Supabase SQL Editorで一度だけ実行してください。
-- 運営者UUIDは既存のGachaLog管理者アカウントに固定しています。

create table if not exists public.product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 100),
  image_url text,
  status text not null default 'pending' check (status in ('pending','published','rejected')),
  submitted_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (product_id, name)
);
create index if not exists product_variants_product_status_idx
  on public.product_variants(product_id,status);

alter table public.product_variants enable row level security;
drop policy if exists "Published variants are readable" on public.product_variants;
create policy "Published variants are readable"
on public.product_variants for select to anon, authenticated
using (status = 'published' or submitted_by = auth.uid());

drop policy if exists "Users can submit variants" on public.product_variants;
create policy "Users can submit variants"
on public.product_variants for insert to authenticated
with check (auth.uid() = submitted_by and status = 'pending');

drop policy if exists "GachaLog admin manages variants" on public.product_variants;
create policy "GachaLog admin manages variants"
on public.product_variants for all to authenticated
using (auth.uid() = '89f33b86-35b8-446b-a0f1-c736c81d3d4b'::uuid)
with check (auth.uid() = '89f33b86-35b8-446b-a0f1-c736c81d3d4b'::uuid);

grant select on public.product_variants to anon, authenticated;
grant insert on public.product_variants to authenticated;
grant update, delete on public.product_variants to authenticated;
grant usage, select on sequence public.product_variants_id_seq to authenticated;

create table if not exists public.user_variant_collections (
  user_id uuid not null references public.profiles(id) on delete cascade,
  variant_id bigint not null references public.product_variants(id) on delete cascade,
  acquired_at date,
  duplicate_count integer not null default 0 check (duplicate_count between 0 and 999),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id,variant_id)
);
create index if not exists user_variant_collections_user_idx
  on public.user_variant_collections(user_id);
create index if not exists user_variant_collections_variant_idx
  on public.user_variant_collections(variant_id);

alter table public.user_variant_collections enable row level security;
drop policy if exists "Variant collections are publicly readable" on public.user_variant_collections;
create policy "Variant collections are publicly readable"
on public.user_variant_collections for select to anon, authenticated
using (auth.uid() = user_id);
drop policy if exists "Users manage their variant collection" on public.user_variant_collections;
create policy "Users manage their variant collection"
on public.user_variant_collections for all to authenticated
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
  and exists (select 1 from public.product_variants v where v.id = variant_id and v.status = 'published')
);
grant select on public.user_variant_collections to anon, authenticated;
grant insert, update, delete on public.user_variant_collections to authenticated;
drop trigger if exists user_variant_collections_updated_at on public.user_variant_collections;
create trigger user_variant_collections_updated_at
before update on public.user_variant_collections
for each row execute procedure public.set_gachalog_updated_at();
