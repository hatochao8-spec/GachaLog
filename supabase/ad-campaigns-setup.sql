-- GachaLog PR / sponsored campaign feature
-- Run this entire file in Supabase SQL Editor.
create table if not exists public.ad_campaigns (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  advertiser text not null check (char_length(advertiser) between 1 and 100),
  description text,
  image_url text,
  target_url text not null check (target_url ~* '^https?://'),
  placement text not null default 'both' check (placement in ('home','catalog','both')),
  start_at timestamptz not null,
  end_at timestamptz not null,
  status text not null default 'active' check (status in ('active','paused','ended')),
  click_count bigint not null default 0,
  created_at timestamptz not null default now(),
  constraint ad_campaign_dates_valid check (end_at > start_at)
);
alter table public.ad_campaigns enable row level security;
drop policy if exists "Anyone can view currently running sponsored campaigns" on public.ad_campaigns;
create policy "Anyone can view currently running sponsored campaigns"
on public.ad_campaigns for select to anon, authenticated
using (status = 'active' and start_at <= now() and end_at > now());
drop policy if exists "Admin can manage sponsored campaigns" on public.ad_campaigns;
create policy "Admin can manage sponsored campaigns"
on public.ad_campaigns for all to authenticated
using (auth.uid() = '89f33b86-35b8-446b-a0f1-c736c81d3d4b'::uuid)
with check (auth.uid() = '89f33b86-35b8-446b-a0f1-c736c81d3d4b'::uuid);
create or replace function public.increment_ad_campaign_click(campaign_id bigint)
returns void language sql security definer set search_path = public
as $$
  update public.ad_campaigns
  set click_count = click_count + 1
  where id = campaign_id and status = 'active'
    and start_at <= now() and end_at > now();
$$;
revoke all on function public.increment_ad_campaign_click(bigint) from public;
grant execute on function public.increment_ad_campaign_click(bigint) to anon, authenticated;
grant select on public.ad_campaigns to anon, authenticated;
grant insert, update, delete on public.ad_campaigns to authenticated;
grant usage, select on sequence public.ad_campaigns_id_seq to authenticated;
