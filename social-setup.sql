-- GachaLog SNS + 図鑑 基本セットアップ
-- Supabase SQL Editor でプロジェクト管理者として一度だけ実行してください。
-- Service Role Key などの秘密情報はここに記載しないでください。

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  display_name text not null default 'ガチャ好き',
  bio text not null default '',
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content text not null default '',
  image_path text,
  product_id bigint references public.products(id) on delete set null,
  status text not null default 'published' check (status in ('pending','published','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint posts_content_or_image check (length(trim(content)) > 0 or image_path is not null)
);

create table if not exists public.post_likes (
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (length(trim(content)) between 1 and 500),
  created_at timestamptz not null default now()
);

create table if not exists public.follows (
  follower_id uuid not null references public.profiles(id) on delete cascade,
  following_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, following_id),
  constraint follows_not_self check (follower_id <> following_id)
);

create index if not exists posts_feed_idx on public.posts (status, created_at desc);
create index if not exists posts_user_idx on public.posts (user_id, created_at desc);
create index if not exists comments_post_idx on public.comments (post_id, created_at asc);
create index if not exists follows_following_idx on public.follows (following_id);

-- 新規Authユーザー作成時にプロフィールを自動生成
create or replace function public.handle_new_gachalog_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  chosen_username text;
begin
  chosen_username := coalesce(
    nullif(trim(new.raw_user_meta_data ->> 'username'), ''),
    'user_' || left(replace(new.id::text, '-', ''), 12)
  );

  insert into public.profiles (id, username, display_name)
  values (
    new.id,
    chosen_username,
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), 'ガチャ好き')
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_gachalog on auth.users;
create trigger on_auth_user_created_gachalog
after insert on auth.users
for each row execute procedure public.handle_new_gachalog_user();

-- updated_at 自動更新
create or replace function public.set_gachalog_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at before update on public.profiles
for each row execute procedure public.set_gachalog_updated_at();

drop trigger if exists posts_updated_at on public.posts;
create trigger posts_updated_at before update on public.posts
for each row execute procedure public.set_gachalog_updated_at();

